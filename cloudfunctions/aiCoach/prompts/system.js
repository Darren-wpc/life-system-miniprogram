const FRAMEWORK_KNOWLEDGE = `
# 生活系统框架（Life System Framework）

本框架由「6 个维度」与「5 个要素」共同构成。维度回答“生活由哪些部分组成”，要素回答“如何让每个部分真正运转起来”。

## 一、6 个维度（Dimension）

维度是生活的六大组成模块，从底层生存到顶层意义，呈金字塔结构，下层是上层的地基。

### 1. survival 生存基础（底层地基）
含义：健康、睡眠、饮食、财务安全、居住稳定等基本生存需求的保障程度。
要点：身体健康状况、睡眠质量、饮食规律、财务安全感、居住与生活稳定性。
判断：生存基础不稳，其他维度的发展都是空中楼阁。任何上层维度的崩溃，往往先在此处出现裂缝。

### 2. autonomy 自主权
含义：对时间、决策、生活方向的掌控感，以及说“不”的能力。
要点：时间自主权、决策自主权、对生活方向的掌控感、拒绝能力。
判断：自主权低意味着被外部力量裹挟，长期会侵蚀内在秩序与意义感。

### 3. capability 能力资产
含义：可复用的技能、知识、经验、专业声誉的积累，是个人立足并产生价值的资本。
要点：核心技能积累、持续学习能力、专业影响力、可迁移能力。
判断：能力资产决定一个人能否把意图转化为现实成果，是中长期发展的引擎。

### 4. relationship 关系支持
含义：能提供情感支持、信息支持、资源支持的真实人际关系网络质量。
要点：亲密关系质量、深层友谊、专业协作网络、社群归属感。
判断：关系不是数量而是质量；高质量关系是缓冲压力、放大能力的杠杆。

### 5. innerOrder 内在秩序
含义：内心稳定感、情绪调节能力、自我认知清晰度，能否在压力下保持方向感。
要点：情绪稳定性、自我认知清晰度、压力调节能力、内在价值锚点。
判断：内在秩序是“软件操作系统”，它失稳时，再多的能力与资源都无法稳定输出。

### 6. meaning 意义贡献（顶层）
含义：感受到生活有超越自身的意义，通过创造、贡献、传承产生的价值感与目的感。
要点：意义感、贡献感、价值创造、对他人/社会的正向影响。
判断：意义贡献是金字塔顶端，但并非可有可无——它反向为下层维度提供持续动力。

## 二、5 个要素（Factor）

要素是让每个维度真正运转起来的“运营机制”。同一套要素作用于全部 6 个维度。

### 1. standards 合适标准
含义：每个维度需要清晰的“什么算够/什么算好”的标准。关键不是高标准，而是“合适”——与当前阶段和能力匹配。
失衡表现：标准模糊（无方向）、标准过高（完美主义导致瘫痪）、标准过低（得过且过导致停滞）。
作用：合适标准是行动的前提，没有它，行动要么不发生，要么盲目。

### 2. action 持续行动
含义：将意图转化为持续、可累积行动的能力。不是偶尔爆发，而是稳定的行动节奏；质量与持续性比强度更重要。
失衡表现：行动瘫痪（想得太多做不动）、三分钟热度（无法持续）、行动与目标脱节（瞎忙）。
作用：行动是把标准落地的唯一途径，也是产生反馈的原材料。

### 3. resources 资源支持
含义：维持和推进每个维度所需的时间、精力、金钱、信息、人际等资源的获取与配置能力。
失衡表现：资源匮乏（巧妇难为无米）、资源错配（投入错地方）、不善求助（孤军奋战）。
作用：没有匹配资源，标准和行动都会很快枯竭。

### 4. feedback 反馈修正
含义：从行动结果中获取反馈、识别偏差、进行调整的能力。包括外部反馈（他人、市场、数据）与内部反馈（身体、情绪、直觉）。
失衡表现：缺乏反馈渠道（蒙眼狂奔）、无视反馈（选择性失明）、反馈后不修正（知错不改）。
作用：反馈修正让行动从“重复”变成“进化”，是避免在错误方向上持续投入的关键。

### 5. uncertainty 接受不确定性
含义：在不确定中依然能行动与决策的心理能力。不因无法预知结果而瘫痪，也不过度追求确定性而错失机会。
失衡表现：过度规划导致不动、风险厌恶导致停滞、虚假确定性依赖（用计划代替行动）。
作用：真实世界充满不确定，这一要素决定了前四个要素能否在现实压力下持续运转。

## 三、维度与要素的关系
- 维度是“横轴”（What：生活的哪些部分），要素是“纵轴”（How：怎样让每个部分运转）。
- 任意一个维度的得分，都可以从 5 个要素去解释：标准是否合适？行动是否持续？资源是否到位？反馈是否修正？能否接受其中的不确定？
- 维度之间存在依赖：生存基础 > 内在秩序 > 自主权 ≈ 能力资产 > 关系支持 > 意义贡献（下层不稳则上层难存）。
- 维度之间也存在失衡：例如能力很高但关系很差、意义很强但生存基础脆弱，失衡本身即是风险信号。

## 四、三种关键分析视角
1. 崩溃点（collapse point）：得分骤降、相互拖累、形成恶性循环的点。常出现在生存基础动摇、内在秩序崩塌，或多个要素同时失灵导致某维度无法维持。
2. 杠杆点（leverage point）：改善后能带动多个维度提升的关键点。通常是最底层最基础的点（如睡眠、核心标准），小投入大效果。
3. 失衡（imbalance）：维度间的失衡（如能力高/关系低）、要素间的失衡（如行动多/反馈缺）。失衡揭示结构性风险。
`

